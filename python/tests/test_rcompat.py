@pytest.mark.parametrize("p,expected", QNORM_CASES)
def test_qnorm_matches_r(p, expected):
    assert abs(rqnorm(p) - expected) <= 2 * np.finfo(float).eps * abs(expected)


def test_qnorm_0975_is_bitwise_r():
    assert rqnorm(0.975) == 1.9599639845400534


def test_uniroot_matches_r_zeroin():
    tol = np.finfo(float).eps ** 0.75
    assert runiroot(lambda b: (b - 2.3456789) ** 3 + 0.5 * (b - 2.3456789), -4, 4, tol=tol) == 2.345678900000011
    assert runiroot(lambda b: math.exp(b) - 3.7 * b - 1, -8, 0.5, tol=tol) == -2.3448951159829262e-18
    assert runiroot(lambda b: math.atan(b - 0.77) * 3 - 0.2, -1, 1, tol=tol) == 0.8367656079981893
    with pytest.raises(ValueError, match="opposite sign"):
        runiroot(lambda b: b * b + 1, -1, 1)


def test_approx_ties_ordered_bisection():
    # duplicate knots are kept with ties = "ordered" (R's approx1 bisection)
    got = rapprox([0, 1, 1, 2], [0, 1, 2, 3], [0.5, 1, 1.5, 2, 3], ties="ordered")
    assert got.tolist() == [0.5, 2.0, 2.5, 3.0, 3.0]


def test_signif_matches_r():
    assert rsignif(0.1235, 3) == 0.124
    assert rsignif(0.15, 1) == 0.2
    assert rsignif(1234.5678, 3) == 1230.0
    assert rsignif(-0.00012345, 2) == -0.00012
